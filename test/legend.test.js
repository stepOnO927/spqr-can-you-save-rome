import test from 'node:test';
import assert from 'node:assert/strict';
import {newGame,upgradeSave} from '../engine.js?v=world-kings-village-foothold-1';
import {createFictionalPerson} from '../dynasties.js?v=world-kings-village-foothold-1';
import {assignLegendPortrait,fictionalPortraitKey} from '../portrait-registry.js?v=world-kings-village-foothold-1';
import {setLegendMode,courtNomineeName,advanceLegend,recordLegendEvidence,earnedEpithets,legendName,legendDossier,grantLegendHonor,EPITHETS} from '../legend.js?v=world-kings-village-foothold-1';
import {CHARACTER_CATALOG} from '../characters.js?v=world-kings-village-foothold-1';
import {renderGenealogyDossier} from '../genealogy-ui.js?v=world-kings-village-foothold-1';
import {sendLetter} from '../epistulae.js?v=world-kings-village-foothold-1';
import {requestAgentRelease,advanceAgentRequests,answerAgentRelease} from '../character-system.js?v=world-kings-village-foothold-1';
const sample=(s,faction=s.player,props={})=>createFictionalPerson(s,{name:['Baldwin of Artaxata','阿尔塔克萨塔的鲍德温'],faction,birthYear:s.year-35,location:s.regions.find(r=>r.owner===faction)?.id||null,sex:'male',origin:'court_nominee',...props});
test('historical mode is default, homage is optional, and catalog identities remain unchanged',()=>{
 const s=newGame('caesar'),historical=[...CHARACTER_CATALOG.caesar.name];
 assert.equal(s.world.legend.mode,'historical');
 assert.equal(courtNomineeName(s,'armenia',1,()=>0).homage,null);
 assert.equal(setLegendMode(s,'homage'),true);
 assert.equal(courtNomineeName(s,'armenia',1,()=>.5).homage,null);
 s.world.legend.frequency=1;
 const generated=courtNomineeName(s,'armenia',1,()=>0);
 assert.equal(generated.homage.fictional,true);
 const id=sample(s,'armenia',{name:generated.name,regnalName:generated.regnalName,homage:generated.homage});
 assert.match(id,/^fictional:/);
 assert.deepEqual(CHARACTER_CATALOG.caesar.name,historical);
 assert.equal(legendDossier(s,id).origin,'fictional_homage');
 assert.equal(setLegendMode(s,'historical'),true);
 assert.equal(courtNomineeName(s,'armenia',2,()=>0).homage,null);
});
test('regnal numbers follow actual predecessors and are stable in saves',()=>{
 let s=newGame('caesar');const a=sample(s,'armenia',{regnalName:['Baldwin','鲍德温']}),b=sample(s,'armenia',{name:['Baldwin of Ancyra','安基拉的鲍德温'],regnalName:['Baldwin','鲍德温']});
 s.world.leadership.armenia=[a];advanceLegend(s);
 assert.match(legendName(s,a,'en','armenia',{formal:true}),/ I$/);
 s.world.characters[a].alive=false;s.world.leadership.armenia=[b];s.month++;advanceLegend(s);
 assert.match(legendName(s,b,'en','armenia',{formal:true}),/ II$/);
 s=upgradeSave(JSON.parse(JSON.stringify(s)));
 assert.match(legendName(s,b,'en','armenia',{formal:true}),/ II$/);
});
test('epithets require dated actions, can differ by audience, and survive save and death',()=>{
 let s=newGame('caesar'),id=sample(s);s.world.characters[id].ambition=100;
 advanceLegend(s);assert.equal(earnedEpithets(s,id).length,0);
 for(let i=0;i<3;i++)recordLegendEvidence(s,id,'maneuver',{reference:'plan:'+i,audiences:['caesar']});
 for(let i=0;i<2;i++)recordLegendEvidence(s,id,'execution',{reference:'sentence:'+i,audiences:['senate']});
 advanceLegend(s);
 assert.equal(earnedEpithets(s,id,'caesar')[0].key,'wolf');
 assert.equal(earnedEpithets(s,id,'senate')[0].key,'executioner');
 assert.match(renderGenealogyDossier(s,id,false),/CAMPAIGN NAMES & REPUTATION/);
 s.world.characters[id].alive=false;recordLegendEvidence(s,id,'power_bid',{reference:'archive:1',audiences:['caesar']});recordLegendEvidence(s,id,'power_bid',{reference:'archive:2',audiences:['caesar']});recordLegendEvidence(s,id,'power_bid',{reference:'archive:3',audiences:['caesar']});advanceLegend(s);
 assert.equal(earnedEpithets(s,id).find(x=>x.key==='ambitionist').posthumous,true);
 s=upgradeSave(JSON.parse(JSON.stringify(s)));assert.equal(earnedEpithets(s,id,'senate')[0].key,'executioner');
});
test('redbeard requires saved appearance and matching portrait',()=>{
 const s=newGame('caesar'),id=sample(s,'caesar',{name:['Frederick of Rome','罗马的腓特烈'],role:['Fictional court nominee in this campaign','本战役虚构宫廷人选']});
 assert.equal(recordLegendEvidence(s,id,'appearance_redbeard'),null);
 s.world.dynasties.catalog[id].appearance={redBeard:true,verifiedPortrait:'fictional-legend-redbeard'};
 assert.equal(assignLegendPortrait(s,id),'fictional-legend-redbeard');
 assert.equal(fictionalPortraitKey(s,id),'fictional-legend-redbeard');
 assert.ok(recordLegendEvidence(s,id,'appearance_redbeard',{reference:'portrait:'+id}));
 advanceLegend(s);assert.equal(earnedEpithets(s,id)[0].key,'redbeard');
});
test('official honors cost treasury, need evidence and do not alter Han legitimacy',()=>{
 const s=newGame('caesar'),id=sample(s);
 const before=s.factions.caesar.treasury;
 assert.equal(grantLegendHonor(s,id,'military').reason,'evidence');
 recordLegendEvidence(s,id,'battle_victory',{reference:'battle:honor'});advanceLegend(s);
 assert.equal(grantLegendHonor(s,id,'military').ok,true);
 assert.equal(s.factions.caesar.treasury,before-5);
 assert.equal(grantLegendHonor(s,id,'military').reason,'already');
 assert.ok(s.world.dynasties.lives[id].some(e=>e.legendHonor));
 assert.equal(s.world.characters[id].faction,'caesar');
});
test('private friendly letters may use earned names; formal diplomatic letters remain formal',()=>{
 const s=newGame('caesar'),id=sample(s);
 for(let i=0;i<3;i++)recordLegendEvidence(s,id,'maneuver',{reference:'letter:'+i});
 advanceLegend(s);
 const personal=sendLetter(s,{senderId:id,senderFaction:'caesar',recipient:'caesar',subject:['Test','测试'],body:['Hello','你好'],category:'personal'});
 assert.equal(personal.ok,true);
 assert.ok(s.mail.messages.some(l=>l.senderId===id&&l.senderName[0].includes('The Wolf')));
 assert.ok(Object.keys(EPITHETS).length>=25);
});
test('a completed captive release creates public mercy evidence; repeated mercy can earn Saint',()=>{
 const s=newGame('caesar');s.world.captives.push({id:'legend-captive-1',owner:'senate',holder:'caesar',state:'held'});
 s.factions.senate.treasury=100;assert.equal(requestAgentRelease(s,'senate','legend-captive-1').ok,true);
 advanceAgentRequests(s);s.world.intelSeed=1000;advanceAgentRequests(s);
 assert.equal(answerAgentRelease(s,'legend-captive-1','release').ok,true);
 advanceAgentRequests(s);s.world.intelSeed=1000;advanceAgentRequests(s);
 assert.equal(s.world.captives.at(-1).state,'released');
 const first=s.world.legend.evidence.find(e=>e.kind==='mercy'&&e.reference?.includes('legend-captive-1'));
 assert.ok(first);assert.ok(first.knownBy.includes('senate'));
 const ruler=s.world.leadership.caesar[0];
 for(let i=2;i<=3;i++)recordLegendEvidence(s,ruler,'mercy',{reference:'mercy-scenario-'+i,audiences:['caesar']});
 recordLegendEvidence(s,ruler,'patronage',{reference:'patronage-scenario',audiences:['caesar']});
 advanceLegend(s);assert.equal(earnedEpithets(s,ruler).find(e=>e.key==='saint')?.support.length,4);
});
