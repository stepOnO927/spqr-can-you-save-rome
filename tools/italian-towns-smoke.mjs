import {chromium} from 'playwright';
import assert from 'node:assert/strict';

const browser=await chromium.launch({headless:true,args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1600,height:1000}}),errors=[];
page.on('pageerror',error=>errors.push(error.message));
const base=`http://127.0.0.1:${process.env.SPQR_SMOKE_PORT||5173}`;
try{
 await page.addInitScript(()=>localStorage.setItem('spqr-lang','en'));
 await page.goto(`${base}/map-lab/`,{waitUntil:'domcontentloaded'});
 await page.evaluate(async()=>{
  const {newGame}=await import('/engine.js?v=dossier-archive-1'),state=newGame('caesar');
  state.armies.find(army=>army.id==='xiii').region='italiaS';
  sessionStorage.setItem('spqr-view-handoff-v1',JSON.stringify({target:'atlas',state}));
 });
 await page.reload({waitUntil:'domcontentloaded'});
 const corfinium=page.locator('.city-marker[data-city="CORFINIUM"]');
 await corfinium.waitFor({state:'visible'});
 const objective=page.locator('[data-town-objective="corfinium"]');
 await objective.waitFor({state:'visible'});
 assert.match(await objective.innerText(),/Secure Corfinium/);
 await objective.evaluate(node=>node.click());
 let panel=page.locator('#command-detail');
 assert.match(await panel.innerText(),/ROMAN TOWN · Corfinium/);
 assert.match(await panel.innerText(),/Domitius Ahenobarbus/);
 assert.match(await panel.innerText(),/Local control: Senate/);
 assert.match(await panel.innerText(),/Source: Caesar, Civil Wars I/);
 await page.locator('#town-route-army').selectOption('viii');
 await page.locator('#town-route-plan').click();
 assert.equal(await page.locator('.route-planner select').inputValue(),'italiaS');
 assert.ok(await page.locator('.route-choice').count()>0);
 await objective.evaluate(node=>node.click());
 panel=page.locator('#command-detail');
 assert.equal(await page.locator('#town-siege').isDisabled(),false);
 await page.locator('#town-siege').click();
 assert.match(await panel.innerText(),/Siege takes/);
 await page.locator('#save').click();
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('spqr-save-1')));
 const town=saved.regions.flatMap(region=>region.localEntities||[]).find(entity=>entity.id==='corfinium');
 assert.equal(town.siege.actor,'caesar');
 assert.equal(town.legalSovereign,'senate');
 assert.equal(saved.regions.find(region=>region.id==='italiaS').owner,'senate');
 assert.equal(saved.armies.find(army=>army.id==='viii').move,null);
 await objective.evaluate(node=>node.click());
 await page.locator('#town-route-army').selectOption('viii');
 await page.locator('#town-route-plan').click();
 await page.locator('.route-choice button').filter({hasText:'START EXPEDITION'}).first().click();
 assert.match(await page.locator('#command-detail').innerText(),/LOCAL OBJECTIVE: Corfinium/);
 await page.locator('#save').click();
 const expeditionSave=await page.evaluate(()=>JSON.parse(localStorage.getItem('spqr-save-1')));
 assert.equal(expeditionSave.armies.find(army=>army.id==='viii').expedition.localObjectiveId,'corfinium');
 assert.equal(expeditionSave.regions.find(region=>region.id==='italiaS').owner,'senate');
 await page.locator('#map-mode').selectOption('expedition');
 assert.match(await page.locator('#map-mode-details').innerText(),/Corfinium/);
 const arrivedState=structuredClone(expeditionSave),arrivedArmy=arrivedState.armies.find(army=>army.id==='viii');
 arrivedArmy.region='italiaS';arrivedArmy.move=null;arrivedArmy.expedition.status='completed';arrivedArmy.expedition.nextIndex=arrivedArmy.expedition.nodes.length;
 await page.evaluate(state=>sessionStorage.setItem('spqr-view-handoff-v1',JSON.stringify({target:'atlas',state})),arrivedState);
 await page.reload({waitUntil:'domcontentloaded'});
 await page.locator('#map-mode').selectOption('expedition');
 assert.match(await page.locator('#map-mode-details').innerText(),/arrived, decision pending · Corfinium/);
 await page.locator('#map-mode-details button').filter({hasText:/arrived, decision pending · Corfinium/}).click();
 assert.match(await page.locator('#command-detail').innerText(),/LOCAL OBJECTIVE: Corfinium/);
 assert.equal(await page.locator('#command-detail button').filter({hasText:'VIEW TOWN'}).count(),1);
 const iguvium=page.locator('.city-marker[data-city="IGUVIUM"]');
 await iguvium.waitFor({state:'visible'});
 await page.locator('[data-town-objective="iguvium"]').evaluate(node=>node.click());
 panel=page.locator('#command-detail');
 assert.match(await panel.innerText(),/ROMAN TOWN · Iguvium/);
 assert.match(await panel.innerText(),/Thermus/);
 for(const [id,name] of [['ariminum','Ariminum'],['capua','Capua'],['brundisium','Brundisium']]){
  const target=page.locator(`[data-town-objective="${id}"]`);
  assert.match(await target.innerText(),new RegExp(`Secure ${name}`));
  await target.evaluate(node=>node.click());
  assert.match(await panel.innerText(),new RegExp(`ROMAN TOWN · ${name}`));
 }
 assert.deepEqual(errors,[]);
 console.log('Five Italian town objectives open sourced local panels; a saved Corfinium siege leaves theater control and legal title distinct.');
}finally{await browser.close()}
