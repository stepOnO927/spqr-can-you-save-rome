import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {resolve,extname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {newGrandGame,proposeKnowledgeSale,proposeKnowledgePurchase} from '../engine.js';
const root=resolve(fileURLToPath(new URL('..',import.meta.url)));
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try{
  await page.route('http://spqr.test/**',async route=>{
    const pathname=new URL(route.request().url()).pathname;
    const file=resolve(root,'.'+(pathname.endsWith('/')?pathname+'index.html':pathname));
    if(!file.startsWith(root))return route.abort();
    const mime={'.js':'text/javascript','.html':'text/html','.css':'text/css','.svg':'image/svg+xml','.json':'application/json','.png':'image/png','.jpg':'image/jpeg'}[extname(file)]||'application/octet-stream';
    try{await route.fulfill({status:200,contentType:mime,body:await readFile(file)})}catch{await route.fulfill({status:404,body:'Not found'})}
  });
  await page.goto('http://spqr.test/',{waitUntil:'domcontentloaded'});
  await page.locator('#entry-continue').click();
  await page.locator('[data-tab="development"]').click();
  assert.match(await page.locator('.inspector h2').innerText(),/Development/);
  await page.locator('[data-dev-branch="idea"]').click();
  assert.match(await page.locator('#tech-sanctuary-protection').innerText(),/Provincial Sanctuary Protection/);
  assert.match(await page.locator('#tech-ancestral-rites').innerText(),/Own rites satisfaction \/ quarter \+1/);
  assert.match(await page.locator('#tech-ancestral-rites').innerText(),/Other rites satisfaction \/ quarter −1/);
  assert.match(await page.locator('#tech-public-legal-reference').innerText(),/Public Legal Reference/);
  assert.match(await page.locator('#tech-citizen-registration').innerText(),/Allied Citizen Registration/);
  assert.match(await page.locator('#tech-civic-exercise').innerText(),/Recruit morale in urban territory with integration ≥65/);
  assert.match(await page.locator('#tech-provincial-autonomy').innerText(),/Treasury \/ month −2/);
  await page.locator('[data-research="legion-training"]').click();
  assert.match(await page.locator('.dev-status').first().innerText(),/Researching/);
  for(let i=0;i<3;i++)await page.locator('#step').click();
  await page.locator('[data-tab="ideas"]').click();
  assert.equal(await page.locator('.dev-category:not(.religion-panel)').count(),5);
  assert.equal(await page.locator('.religion-panel').count(),1);
  await page.locator('[data-adopt-idea="legion-training"]').first().click();
  for(let i=0;i<2;i++)await page.locator('#step').click();
  assert.match(await page.locator('.dev-slot').first().innerText(),/Legion Field Training/);
  await page.locator('[data-tab="map"]').click();
  await page.locator('#region-choice').selectOption('gaul');
  assert.ok(await page.locator('[data-build="road"]').count());
  const stoneBefore=await page.locator('.dev-construction .dev-meta').first().innerText();
  if(await page.locator('[data-buy-material="stone"]').isEnabled()){
    await page.locator('[data-buy-material="stone"]').click();
    assert.notEqual(await page.locator('.dev-construction .dev-meta').first().innerText(),stoneBefore);
  }
  await page.locator('#lang').click();
  await page.locator('[data-tab="development"]').click();
  assert.match(await page.locator('.inspector h2').innerText(),/文明发展/);
  await page.locator('[data-dev-branch="idea"]').click();
  assert.match(await page.locator('#tech-sanctuary-protection').innerText(),/行省圣所保护/);
  assert.match(await page.locator('#tech-ancestral-rites').innerText(),/传统祭仪扶持/);
  assert.match(await page.locator('#tech-ancestral-rites').innerText(),/异地祭仪满意度 \/ 季 −1/);
  assert.match(await page.locator('#tech-public-legal-reference').innerText(),/公开法律参照/);
  assert.match(await page.locator('#tech-citizen-registration').innerText(),/盟邦公民登记/);
  assert.match(await page.locator('#tech-civic-exercise').innerText(),/融合度≥65的城市新兵士气/);
  assert.match(await page.locator('#tech-provincial-autonomy').innerText(),/国库 \/ 月 −2/);
  await page.screenshot({path:'tools/phase-xiv-ui.png'});
  for(const lang of ['en','zh']){
    const replacing=newGrandGame('caesar');
    replacing.development.caesar.knownIdeas.push('hardline-diplomacy','diplomatic-accommodation');
    replacing.development.caesar.slots.diplomacy[0]='hardline-diplomacy';
    await page.evaluate(language=>localStorage.setItem('spqr-lang',language),lang);
    await page.goto('http://spqr.test/',{waitUntil:'domcontentloaded'});
    await page.locator('#entry-file').setInputFiles({name:`replace-${lang}.json`,mimeType:'application/json',buffer:Buffer.from(JSON.stringify(replacing))});
    await page.locator('[data-tab="ideas"]').click();
    const replacement=page.locator('[data-adopt-idea="diplomatic-accommodation"][data-slot="0"]');
    assert.equal(await replacement.isEnabled(),true,lang);
    await replacement.click();
    for(let i=0;i<3;i++)await page.locator('#step').click();
    assert.match(await page.locator('.dev-category:not(.religion-panel)').nth(2).locator('.dev-slot').first().innerText(),lang==='zh'?/外交妥协/:/Diplomatic Accommodation/);
  }
  for(const lang of ['en','zh']){
    const rites=newGrandGame('caesar');rites.wars=[];rites.factions.caesar.treasury=500;
    rites.development.caesar.knownIdeas.push('ancestral-rites');
    await page.evaluate(language=>localStorage.setItem('spqr-lang',language),lang);
    await page.goto('http://spqr.test/',{waitUntil:'domcontentloaded'});
    await page.locator('#entry-file').setInputFiles({name:`rites-${lang}.json`,mimeType:'application/json',buffer:Buffer.from(JSON.stringify(rites))});
    await page.locator('[data-tab="ideas"]').click();
    const button=page.locator('[data-adopt-idea="ancestral-rites"][data-slot="0"]');
    assert.equal(await button.isEnabled(),true,lang);
    await button.click();
    for(let i=0;i<3;i++)await page.locator('#step').click();
    assert.match(await page.locator('.dev-category:not(.religion-panel)').nth(4).locator('.dev-slot').first().innerText(),lang==='zh'?/传统祭仪扶持/:/Ancestral Rites Patronage/);
  }
  const offered=newGrandGame('senate');offered.relations['egypt:senate']=20;
  assert.equal(proposeKnowledgeSale(offered,'egypt','senate','material','water-control').ok,true);
  await page.evaluate(()=>localStorage.setItem('spqr-lang','en'));
  await page.goto('http://spqr.test/',{waitUntil:'domcontentloaded'});
  await page.locator('#entry-file').setInputFiles({name:'offer.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(offered))});
  await page.locator('[data-tab="development"]').click();
  assert.equal(await page.locator('[data-accept-offer-seller="egypt"]').count(),1);
  assert.match(await page.locator('.dev-build-row').filter({has:page.locator('[data-accept-offer-seller="egypt"]')}).innerText(),/Egypt/);
  assert.match(await page.locator('[data-accept-offer-seller="egypt"]').innerText(),/Accept/);
  await page.locator('[data-accept-offer-seller="egypt"]').click();
  assert.equal(await page.locator('[data-accept-offer-seller="egypt"]').count(),0);
  assert.match(await page.locator('.dev-status').allInnerTexts().then(x=>x.join(' ')),/Water Management/);
  const declined=newGrandGame('senate');declined.relations['egypt:senate']=20;
  assert.equal(proposeKnowledgeSale(declined,'egypt','senate','material','water-control').ok,true);
  await page.evaluate(()=>localStorage.setItem('spqr-lang','zh'));
  await page.goto('http://spqr.test/',{waitUntil:'domcontentloaded'});
  await page.locator('#entry-file').setInputFiles({name:'offer-zh.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(declined))});
  await page.locator('[data-tab="development"]').click();
  assert.match(await page.locator('.dev-build-row').filter({has:page.locator('[data-decline-offer-seller="egypt"]')}).innerText(),/埃及/);
  assert.match(await page.locator('[data-decline-offer-seller="egypt"]').innerText(),/拒绝/);
  await page.locator('[data-decline-offer-seller="egypt"]').click();
  assert.equal(await page.locator('[data-decline-offer-seller="egypt"]').count(),0);
  await page.evaluate(state=>sessionStorage.setItem('spqr-view-handoff-v1',JSON.stringify({target:'atlas',state})),offered);
  await page.goto('http://spqr.test/map-lab/',{waitUntil:'domcontentloaded'});
  await page.locator('#development').click();
  assert.equal(await page.locator('[data-accept-offer-seller="egypt"]').count(),1);
  await page.locator('[data-accept-offer-seller="egypt"]').click();
  assert.equal(await page.locator('[data-accept-offer-seller="egypt"]').count(),0);
  const requested=newGrandGame('egypt');requested.relations['caesar:egypt']=40;requested.factions.caesar.treasury=200;
  assert.equal(proposeKnowledgePurchase(requested,'caesar','egypt','material','water-control').ok,true);
  for(const language of ['en','zh']){
    await page.evaluate(value=>localStorage.setItem('spqr-lang',value),language);
    await page.goto('http://spqr.test/',{waitUntil:'domcontentloaded'});
    await page.locator('#entry-file').setInputFiles({name:`request-${language}.json`,mimeType:'application/json',buffer:Buffer.from(JSON.stringify(requested))});
    await page.locator('[data-tab="development"]').click();
    const request=page.locator('.dev-build-row').filter({has:page.locator('[data-accept-purchase-buyer="caesar"]')});
    assert.match(await request.innerText(),language==='zh'?/凯撒.*请求购买己方知识/:/Caesar.*requests your knowledge/);
    if(language==='zh')await page.locator('[data-decline-purchase-buyer="caesar"]').click();
    else await page.locator('[data-accept-purchase-buyer="caesar"]').click();
    assert.equal(await page.locator('[data-accept-purchase-buyer="caesar"]').count(),0);
  }
  await page.evaluate(state=>sessionStorage.setItem('spqr-view-handoff-v1',JSON.stringify({target:'atlas',state})),requested);
  await page.goto('http://spqr.test/map-lab/',{waitUntil:'domcontentloaded'});
  await page.locator('#development').click();
  assert.equal(await page.locator('[data-accept-purchase-buyer="caesar"]').count(),1);
  await page.locator('[data-accept-purchase-buyer="caesar"]').click();
  assert.equal(await page.locator('[data-accept-purchase-buyer="caesar"]').count(),0);
  assert.deepEqual(errors,[]);
  console.log('Phase XIV browser smoke passed: research, adoption, construction and consent-based knowledge sales and purchases in both languages.');
}finally{await browser.close()}
