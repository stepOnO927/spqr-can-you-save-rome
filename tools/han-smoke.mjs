import {chromium} from 'playwright';
import assert from 'node:assert/strict';

const base=process.env.SPQR_URL||'http://127.0.0.1:5173';
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1600,height:900}});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
try{
 await page.addInitScript(()=>localStorage.setItem('spqr-lang','zh'));
 await page.goto(base+'/',{waitUntil:'domcontentloaded'});
 await page.locator('#faction-choice').selectOption('han');
 assert.equal(await page.locator('#faction-choice').inputValue(),'han');
 await page.locator('#start-campaign').click();
 await page.waitForURL('**/map-lab/');
 await page.locator('[data-theater="hanGuanzhong"]').waitFor();
 await page.locator('[data-theater="shanshanOasis"]').waitFor();
 assert.match(await page.locator('.brief h1').innerText(),/关中/);
 assert.match(await page.locator('#objectives').innerText(),/河西走廊/);
 await page.locator('#factions').click();
 await page.locator('[data-faction="shanshan"]').click();
 assert.match(await page.locator('#selection-title').innerText(),/鄯善/);
 await page.locator('#factions').click();
 await page.locator('[data-faction="han"]').click();
 assert.match(await page.locator('#command-detail').innerText(),/西汉朝廷任命/);
 assert.match(await page.locator('#command-detail').innerText(),/赵和/);
 await page.locator('[data-office-choice="finance"]').selectOption({label:'王桓'});
 await page.locator('[data-office-appoint="finance"]').click();
 await page.locator('#office-feedback button').click();
 assert.match(await page.locator('.office-row').first().innerText(),/王桓/);
 assert.equal(await page.locator('[data-army="hanCapitalGuard"]').count(),1);
 await page.locator('[data-army="hanCapitalGuard"]').click({force:true});
 assert.match(await page.locator('#selection-detail').innerText(),/张守/);
 assert.match(await page.locator('#command-detail').innerText(),/8,500/);
 await page.locator('#lab-orders select').selectOption('hanHexi');
 assert.match(await page.locator('.preview-detail').innerText(),/河西走廊/);
 await page.locator('#lab-orders button').click();
 await page.locator('#advance').click();
 await page.locator('#advance').click();
 await page.locator('[data-army="hanCapitalGuard"]').click({force:true});
 assert.match(await page.locator('#command-detail').innerText(),/河西走廊/);
 await page.locator('#command-detail .identity-focus-map').first().click();
 assert.match(await page.locator('#selection-title').innerText(),/张守/);
 await page.locator('#save-slot').selectOption('2');
 await page.locator('#save').click();
 await page.goto(base+'/',{waitUntil:'domcontentloaded'});
 await page.locator('#slot-choice').selectOption('2');
 await page.locator('[data-slot="load"]').click();
 await page.locator('#open-atlas').click();
 await page.waitForFunction(()=>document.querySelector('[data-theater="hanGuanzhong"]')&&document.querySelector('.brief h1')?.textContent.includes('关中'));
 await page.locator('[data-army="hanCapitalGuard"]').click({force:true});
 assert.match(await page.locator('#selection-detail').innerText(),/张守/);
 await page.locator('#factions').click();
 await page.locator('[data-faction="han"]').click();
 assert.match(await page.locator('.office-row').first().innerText(),/王桓/);
 await page.locator('#language').click();
 assert.match(await page.locator('.brief h1').textContent(),/Guanzhong/);
 assert.deepEqual(errors,[]);
 console.log('Han browser smoke passed: setup, atlas, command, march, profile, save/load, English and Chinese.');
}catch(error){console.error('Han smoke context:',{url:page.url(),errors,heading:await page.locator('.brief h1').textContent().catch(()=>null),markers:await page.locator('[data-theater]').count(),handoff:await page.evaluate(()=>{try{const x=JSON.parse(sessionStorage.getItem('spqr-view-handoff-v1'));return x&&{target:x.target,player:x.state?.player}}catch{return null}})});throw error}finally{await browser.close()}
