import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try{
 await page.addInitScript(()=>{if(!localStorage.getItem('spqr-lang'))localStorage.setItem('spqr-lang','zh')});
 await page.goto('http://127.0.0.1:5173/',{waitUntil:'domcontentloaded'});
 await page.locator('.setup-panel').waitFor();
 await page.locator('#campaign-difficulty').selectOption('travel');
 assert.match(await page.locator('#campaign-difficulty').locator('option:checked').innerText(),/旅行/);
 await page.locator('#start-campaign').click();
 await page.waitForURL('**/map-lab/');
 await page.locator('#guide:not([hidden])').waitFor({timeout:60000});
 await page.locator('#guide-skip').click();
 await page.locator('#feather-counsel:not([hidden])').waitFor();
 assert.match(await page.locator('#feather-counsel').innerText(),/羽毛/);
 await page.locator('#save').click();
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('spqr-save-1')));
 assert.equal(saved.difficulty,'travel');
 assert.ok(saved.factions.caesar.treasury>=400);
 assert.equal(saved.armies.filter(a=>a.owner==='caesar'&&a.name[0]==='Travel legion').length,3);
 assert.equal(Object.keys(saved.world.offices.caesar).length,3);
 await page.locator('#advance').click();
 assert.match(await page.locator('#feather-counsel').innerText(),/羽毛/);
 await page.locator('#language').click();
 assert.match(await page.locator('#feather-counsel').innerText(),/FEATHER/);
 await page.locator('#return-campaign').click();
 await page.waitForURL('http://127.0.0.1:5173/');
 assert.match(await page.locator('.feather-panel').innerText(),/FEATHER/);
 assert.deepEqual(errors,[]);
 console.log('Travel setup, staffed campaign, Feather guidance, language, turn and cross-view handoff passed');
}finally{await browser.close()}
