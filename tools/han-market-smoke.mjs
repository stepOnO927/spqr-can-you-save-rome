import {chromium} from 'playwright';
import assert from 'node:assert/strict';

const base=process.env.SPQR_URL||'http://127.0.0.1:5173';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[];
page.on('pageerror',error=>errors.push(error.message));
try{
 await page.addInitScript(()=>{localStorage.setItem('spqr-han-lang','en');Date.now=()=>123456});
 await page.goto(base+'/han/',{waitUntil:'domcontentloaded'});
 await page.locator('#factionSelect').selectOption('han');await page.locator('#begin').click();
 await page.locator('#trade-panel').click();
 assert.match(await page.locator('#inspector').innerText(),/Own stock/);
 await page.locator('[data-export-good="silk"]').click();
 assert.match(await page.locator('#message').innerText(),/Export policy updated/);
 assert.equal(await page.locator('[data-export-good="silk"]').getAttribute('aria-pressed'),'true');
 await page.locator('#east-market-sale-good').selectOption('grain');
 assert.match(await page.locator('#east-market-sale-stock').innerText(),/Available stock [1-9]/);
 await page.locator('#east-market-sale-post').click();
 assert.match(await page.locator('#message').innerText(),/Goods reserved and offered/);
 assert.equal(await page.locator('[data-cancel-sale]').count(),1);
 await page.locator('#east-market-tariff').selectOption('high');
 assert.match(await page.locator('#message').innerText(),/Customs policy updated/);
 assert.equal(await page.locator('#east-market-tariff').inputValue(),'high');
 await page.locator('#east-market-partner').selectOption('kangju');await page.locator('#east-market-propose').click();
 assert.match(await page.locator('#message').innerText(),/accepted/);
 const value=await page.locator('#east-market-offer option').evaluateAll(options=>options.find(o=>o.textContent.includes('Kangju')&&o.textContent.includes('Horses'))?.value);
 assert.ok(value,'Kangju horses should become available after a market agreement');
 await page.locator('#east-market-offer').selectOption(value);
 await page.locator('#east-market-destination').selectOption('dunhuang');
 const quoteText=await page.locator('#east-market-quote').innerText(),months=Number(quoteText.match(/Travel (\d+) months/)?.[1]);
 assert.ok(months>0,quoteText);
 assert.equal(await page.locator('#east-market-order').isDisabled(),false);
 await page.locator('#east-market-order').click();
 assert.match(await page.locator('#message').innerText(),/Merchant dispatched/);
 assert.match(await page.locator('.market-shipment').filter({hasText:'Horses'}).first().innerText(),/Horses/);
 await page.locator('#save').click();await page.reload({waitUntil:'domcontentloaded'});await page.locator('#load').click();await page.locator('#trade-panel').click();
 assert.equal(await page.locator('[data-cancel-sale]').count(),1);
 await page.locator('[data-cancel-sale]').click();
 assert.match(await page.locator('#message').innerText(),/stock returned/);
 assert.equal(await page.locator('[data-export-good="silk"]').getAttribute('aria-pressed'),'true');
 await page.locator('[data-export-good="silk"]').click();
 assert.equal(await page.locator('[data-export-good="silk"]').getAttribute('aria-pressed'),'false');
 assert.equal(await page.locator('#east-market-tariff').inputValue(),'high');
 assert.match(await page.locator('.market-shipment').filter({hasText:'Horses'}).first().innerText(),/Horses/);
 for(let i=0;i<months+2;i++)await page.locator('#advance').click();
 assert.match(await page.locator('.market-shipment').filter({hasText:'Horses'}).first().innerText(),/Delivered/);
 assert.match(await page.locator('.market-receipts').innerText(),/Kangju.*Dunhuang/);
 assert.match(await page.locator('.market-receipts').innerText(),/Goods.*Transport.*Tariffs.*Total/);
 await page.locator('#lang').click();assert.match(await page.locator('#inspector').innerText(),/关市与商队/);
 assert.match(await page.locator('#inspector').innerText(),/过境关税/);
 assert.match(await page.locator('#inspector').innerText(),/出口管制/);
 assert.match(await page.locator('#inspector').innerText(),/挂牌出售/);
 assert.match(await page.locator('.market-receipts').innerText(),/货价.*运费.*过境税.*总计/);
 await page.evaluate(async()=>{
  const {newHanGame,serialize,SAVE_KEY}=await import('/han/engine.js');
  const {propose,declareWar}=await import('/han/frontier.js?v=han-1');
  const {placeEasternTrade,advanceEasternMarkets}=await import('/han/markets.js?v=faces-of-empire-1');
  const state=newHanGame('han',{seed:77});
  if(propose(state,'han','kangju','market').proposal.status!=='accepted')throw Error('Market treaty unavailable');
  const placed=placeEasternTrade(state,{seller:'kangju',buyer:'han',origin:'kangju',destination:'dunhuang',commodity:'horses',quantity:1});
  if(!placed.ok||!declareWar(state,'han','kangju').ok)throw Error('Blockade setup failed');
  for(let i=0;i<13;i++){if(++state.month>12){state.month=1;state.year++}advanceEasternMarkets(state)}
  if(placed.shipment.status!=='stranded')throw Error('Blocked caravan did not settle');
  localStorage.setItem(SAVE_KEY('browser'),serialize(state));
 });
 await page.locator('#load').click();await page.locator('#trade-panel').click();
 assert.match(await page.locator('.market-receipts').innerText(),/封路后退回.*货物退回.*退款.*运费支出/s);
 await page.locator('#lang').click();
 assert.match(await page.locator('.market-receipts').innerText(),/Returned after blockade.*Goods returned to.*Refund.*Transport spent/s);
 assert.deepEqual(errors,[]);
 console.log('Han market browser smoke passed: measured sale listing, customs and export policy, treaty, horse dispatch, delivery and bilingual panel.');
}finally{await browser.close()}
