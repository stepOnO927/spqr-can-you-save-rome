import {chromium} from 'playwright';
import assert from 'node:assert/strict';

const browser=await chromium.launch({headless:true,args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[];
page.on('pageerror',error=>errors.push(error.message));
try{
 await page.addInitScript(()=>{localStorage.setItem('spqr-lang','en');localStorage.removeItem('spqr-onboarded')});
 await page.goto(`${process.env.SPQR_URL||'http://127.0.0.1:5173'}/map-lab/`,{waitUntil:'domcontentloaded'});
 await page.locator('#start-overlay:not([hidden])').waitFor({timeout:30000});
 await page.locator('#start-free').click();
 await page.waitForFunction(()=>document.querySelector('#status')?.style.display==='none',{timeout:30000});
 await page.locator('[data-city="NARBO"]').evaluate(el=>el.click());
 await page.locator('#city-region').click();
 const panel=page.locator('#civilization-panel');await panel.waitFor();
 await page.locator('#inventions').click();
 await page.locator('#invention-screen:not([hidden])').waitFor();
 assert.match(await page.locator('#invention-screen').innerText(),/MATERIAL INVENTIONS/);
 await page.locator('#invention-close').click();
 assert.ok(await page.locator('#construct-start').count());
 assert.match(await panel.innerText(),/CIVILIZATION DEVELOPMENT|Population/);
 assert.ok(await panel.locator('.building-art').count());
 assert.match(await panel.locator('#civil-building-detail a').getAttribute('href'),/^https:\/\//);
 const initialPopulation=(await panel.innerText()).match(/Population\s+([\d,]+)/)?.[1];
 await panel.locator('#civil-building').selectOption('granary');
 await panel.locator('#civil-build').click();
 assert.match(await page.locator('#civilization-panel').innerText(),/Granary · 4 mo/);
 await page.locator('#civil-policy').selectOption('accommodation');
 await page.locator('#civil-policy-apply').click();
 await page.locator('#civil-figure').selectOption('vitruvius');
 await page.locator('#civil-role').selectOption('engineer');
 await page.locator('#civil-recruit').click();
 for(let i=0;i<4;i++)await page.locator('#advance').click();
 await page.locator('[data-city="NARBO"]').evaluate(el=>el.click());await page.locator('#city-region').click();
 const later=await page.locator('#civilization-panel').innerText();
 assert.match(later,/Granary/);
 assert.doesNotMatch(later,/Granary · \d+ mo/);
 assert.notEqual(later.match(/Population\s+([\d,]+)/)?.[1],initialPopulation);
 await page.locator('#map-mode').selectOption('satisfaction');
 assert.match(await page.locator('#map-mode-note').innerText(),/satisfaction/i);
 await page.locator('#map-mode').selectOption('infrastructure');
 assert.match(await page.locator('#map-mode-note').innerText(),/buildings/i);
 await page.locator('#language').click();
 assert.match(await page.locator('#civilization-panel').innerText(),/文明发展|人口满意度/);
 assert.match(await page.locator('#civilization-panel').innerText(),/粮仓/);
 await page.locator('#save-slot').selectOption('3');await page.locator('#save').click();await page.locator('#load').click();
 await page.locator('[data-city="NARBO"]').evaluate(el=>el.click());await page.locator('#city-region').click();
 assert.match(await page.locator('#civilization-panel').innerText(),/粮仓/);
 assert.deepEqual(errors,[]);
 console.log('Phase XIII browser smoke passed: construction, religion, specialist, time, population, map modes, bilingual save/load.');
}finally{await browser.close()}
