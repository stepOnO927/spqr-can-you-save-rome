import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {newGame,tick} from '../engine.js?v=world-kings-city-diplomacy-2';
import {configureStartingDifficulty} from '../difficulty.js?v=world-kings-city-diplomacy-2';
import {playableLocalCities,startLocalCampaign,localProtectionOffer} from '../local-campaign.js?v=world-kings-city-diplomacy-2';

const browser=await chromium.launch({headless:true,...(process.env.SPQR_BROWSER_EXECUTABLE?{executablePath:process.env.SPQR_BROWSER_EXECUTABLE}:{}),args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1600,height:1000}}),errors=[];
page.on('pageerror',error=>errors.push(error.message));
const base=`http://127.0.0.1:${process.env.SPQR_SMOKE_PORT||5173}`;
try{
 await page.addInitScript(()=>localStorage.setItem('spqr-lang','en'));
 await page.goto(`${base}/`,{waitUntil:'domcontentloaded'});
 const option=page.locator('#faction-choice option[value^="generated:"]').first();
 await option.waitFor({state:'attached'});const id=await option.getAttribute('value');assert.ok(id);
 await page.selectOption('#faction-choice',id);
 await page.click('#start-campaign');
 await page.locator('.local-council').waitFor();
 assert.match(await page.locator('.local-council').innerText(),/You govern an autonomous city/);
 await page.locator('[data-local-trade]').click();
 if(await page.locator('[data-local-recruit]').isEnabled())await page.locator('[data-local-recruit]').click();
 await page.locator('#step').click();
 await page.locator('#step').click();
 await page.locator('[data-local-protection]').click();
 assert.match(await page.locator('.local-council').innerText(),/Protection request in transit/);
 for(let month=0;month<3;month++)await page.locator('#step').click();
 const council=await page.locator('.local-council').innerText();
 assert.doesNotMatch(council,/Protection request in transit/);
 assert.match(council,/Protected by|city remains independent/);
 await page.locator('#mail-open').click();
 assert.match(await page.locator('.mailbox').innerText(),/Reply to the protection request/);
 await page.locator('#mail-close').click();
 await page.locator('#new').click();
 await page.locator('[data-slot="save"]').click();
 const cityName=await page.evaluate(id=>JSON.parse(localStorage.getItem('spqr-save-1')).regions.flatMap(region=>region.localEntities||[]).find(city=>city.id===id).name[0].toUpperCase(),id);
 await page.locator('#open-atlas').click();
 await page.waitForURL('**/map-lab/');
 const ownMarker=page.locator(`.city-marker[data-city="${cityName}"]`);
 await ownMarker.waitFor({state:'visible'});
 await ownMarker.click();
 assert.match(await page.locator('#command-detail').innerText(),/City council|CITY COUNCIL|You govern an autonomous city/);
 await page.locator('#save').click();
 await page.locator('.mast a').click();
 await page.waitForURL(base+'/');
 await page.locator('.local-council').waitFor();
 assert.ok((await page.locator('.local-council').innerText()).includes('Completed trades'));
 const prepared=configureStartingDifficulty(newGame('caesar'),'standard',false,{localSeed:273});
 const preparedCity=playableLocalCities(prepared)[0],preparedHost=prepared.regions.find(region=>region.id===preparedCity.theater).owner;
 startLocalCampaign(prepared,preparedCity.id);assert.equal(localProtectionOffer(prepared),true);
 for(let month=0;month<3;month++)tick(prepared);
 assert.equal(preparedCity.overlord,preparedHost);
 prepared.relations[[preparedCity.id,preparedHost].sort().join(':')]=30;
 await page.evaluate(value=>sessionStorage.setItem('spqr-view-handoff-v1',JSON.stringify({target:'campaign',state:value})),prepared);
 await page.goto(`${base}/`,{waitUntil:'domcontentloaded'});
 await page.locator('[data-local-independence]').click();
 assert.match(await page.locator('.local-council').innerText(),/Independence petition in transit/);
 await page.locator('#step').click();await page.locator('#step').click();
 assert.match(await page.locator('.local-council').innerText(),/city remains independent/);
 await page.locator('#mail-open').click();
 assert.match(await page.locator('.mailbox').innerText(),/Reply to the independence petition/);
 await page.locator('#mail-close').click();
 await page.locator('#new').click();await page.locator('[data-slot="save"]').click();
 const released=await page.evaluate(id=>JSON.parse(localStorage.getItem('spqr-save-1')).regions.flatMap(region=>region.localEntities||[]).find(city=>city.id===id).overlord,preparedCity.id);
 assert.equal(released,null);
 assert.equal(errors.length,0,errors.join('\n'));
 console.log('Local campaign, protection and independence replies, save, Map Lab handoff and return passed');
}finally{await browser.close()}
