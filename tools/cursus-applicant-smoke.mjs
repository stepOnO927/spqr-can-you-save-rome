import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1366,height:768}});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
try{
 await page.addInitScript(()=>localStorage.setItem('spqr-lang','zh'));
 await page.goto('http://127.0.0.1:5173/',{waitUntil:'domcontentloaded'});
 await page.evaluate(async()=>{
  const engine=await import('/engine.js?v=cursus-integrated-1');
  const politics=await import('/cursus-honorum.js?v=cursus-integrated-1');
  const state=engine.newGame('senate'),c=politics.initializeCursus(state);
  c.talents.push({actor:'senate',id:c.varroId,field:'provincial',regionId:'roma',year:state.year,month:state.month});
  sessionStorage.setItem('spqr-view-handoff-v1',JSON.stringify({target:'atlas',state}));
 });
 await page.goto('http://127.0.0.1:5173/map-lab/',{waitUntil:'domcontentloaded'});
 await page.locator('#factions').click();
 await page.locator('[data-faction="senate"]').click();
 await page.locator('.cursus-talent > summary').click();
 await page.locator('[data-cursus-zoom]').selectOption('80');
 assert.equal(await page.locator('.cursus-offices').evaluate(el=>el.style.zoom),'80%');
 const talent=page.locator('.cursus-talent-person').filter({hasText:'卢基乌斯·瓦罗'});
 assert.equal(await talent.count(),1);
 await talent.locator('.cursus-application-actions summary').click();
 await talent.locator('[data-applicant-review="interview"]').click();
 await page.locator('#save').click();
 let saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('spqr-save-1')));
 assert.equal(saved.world.cursus.applicationReviews.at(-1).status,'pending');
 await page.locator('#advance').click();
 await page.locator('#save').click();
 saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('spqr-save-1')));
 assert.equal(saved.world.cursus.applicationReviews.at(-1).status,'complete');
 assert.ok(saved.world.cursus.applicationReviews.at(-1).report);
 await page.locator('#load').click();
 await page.locator('#save').click();
 saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('spqr-save-1')));
 assert.equal(saved.world.cursus.applicationReviews.at(-1).status,'complete');
 await page.locator('#factions').click();
 await page.locator('[data-faction="senate"]').click();
 await page.locator('.cursus-talent > summary').click();
 const after=page.locator('.cursus-talent-person').filter({hasText:'卢基乌斯·瓦罗'});
 await after.locator('.cursus-application-actions summary').click();
 assert.match(await after.innerText(),/面谈.*已完成/);
 await page.locator('#language').click();
 await page.locator('#factions').click();
 await page.locator('[data-faction="senate"]').click();
 await page.locator('.cursus-talent > summary').click();
 assert.match(await page.locator('.cursus-talent-person').first().innerText(),/APPLICATION REVIEW/);
 await page.setViewportSize({width:600,height:800});
 assert.equal(await page.locator('[data-cursus-zoom]').inputValue(),'80');
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-window.innerWidth);
 assert.ok(overflow<=1,'600px campaign atlas must not cause page-wide horizontal scrolling: '+overflow);
 assert.deepEqual(errors,[]);
 console.log('Applicant interview, month resolution, save/load and bilingual controls passed in cloud browser');
}finally{await browser.close()}
